// ============================================================
// 类型定义
// ============================================================

/** 神话生物属性块 */
export interface MythosCreature {
  id: string;
  /** 中文名 */
  name: string;
  /** 英文名（原文参考） */
  nameEn: string;
  /** 生命值 */
  hp: number;
  maxHp: number;
  /** 护甲等级 */
  ac: number;
  /** 力量 (3–18+，非人类可达数十) */
  str: number;
  /** 体质 */
  con: number;
  /** 敏捷 */
  dex: number;
  /** 意志力 */
  pow: number;
  /** 基础体型 — 决定伤害加值和生命值 */
  siz: number;
  /** 每轮移动值 */
  mov: number;
  /** 伤害公式 (e.g. "1d6+1d4") */
  damage: string;
  /** 物理伤害减免（护甲值） */
  armor: number;
  /** 标志性技能 */
  skills: string[];
  /** 目睹时的 SAN 损失 (格式: "成功损失/失败损失") */
  sanLoss: string;
  /** 战斗行为标签 — 对应 coc-npc.yaml 中的 creatures 表 */
  tactics?: string;
  /** 能力列表 */
  abilities: string[];
  /** 弱点 */
  weaknesses: string[];
  /** 自撰描述 */
  description: string;
  /** 出处（洛夫克拉夫特作品） */
  source: string;
}

/** 神话典籍 */
interface MythosTome {
  id: string;
  name: string;
  nameEn: string;
  /** SAN 消耗 (格式: "阅读损失/钻研损失") */
  sanCost: string;
  /** 研读所需时间 */
  studyTime: string;
  /** 可能学到的法术 */
  spellsTaught: string[];
  /** 是否已在已存在的数据中引用 */
  alreadySeeded?: boolean;
  /** 自撰描述 */
  description: string;
  /** 出处 */
  source: string;
}

/** 神话法术定义 — 扩展 GameSession.MythosSpell，增加 nameEn/effectType/source */
interface MythosSpellDef {
  name: string;
  nameEn: string;
  /** SAN 消耗格式 "1d4" 或 "1/1d8"（检定成功/失败） */
  sanCost: string;
  /** 魔力消耗 */
  mpCost: number;
  /** 法术效果类型 */
  effectType: "summon" | "bind" | "damage" | "curse" | "transfer" | "disguise" | "banish" | "perception" | "other";
  /** 法术效果描述 */
  description: string;
  /** 出处 */
  source: string;
}

